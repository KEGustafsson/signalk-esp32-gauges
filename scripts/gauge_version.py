"""The firmware's version, from the repository's VERSION file.

VERSION holds one line, the version both boards' firmware reports (e.g.
0.1.0): in the boot log, on the gauge's info overlay and on the web UI's
Status page. This pre: script writes it into common/src/gauge_version_value.h
(generated, gitignored), which only common/src/gauge_version.cpp includes:
a new version recompiles that one file, not the firmware (a -D flag would
be on every compile command and recompile everything). The header is
rewritten only when the version changes, so an unchanged one rebuilds
nothing.
"""

import os
import re
import sys

Import("env")  # noqa: F821 -- injected by SCons

VERSION_RE = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.-]+)?")


def main():
    root = os.path.normpath(os.path.join(env.subst("$PROJECT_DIR"), ".."))  # noqa: F821
    version_file = os.path.join(root, "VERSION")
    try:
        with open(version_file, encoding="utf-8") as f:
            version = f.read().strip()
    except OSError:
        print("gauge_version: %s not found" % version_file, file=sys.stderr)
        env.Exit(1)  # noqa: F821
        return
    if not VERSION_RE.fullmatch(version):
        print("gauge_version: %s must hold a version like 0.1.0, not %r"
              % (version_file, version), file=sys.stderr)
        env.Exit(1)  # noqa: F821
        return

    header = os.path.join(root, "common", "src", "gauge_version_value.h")
    text = ("// Generated by scripts/gauge_version.py from VERSION; do not edit.\n"
            "#define GAUGE_FIRMWARE_VERSION \"%s\"\n" % version)
    current = None
    if os.path.isfile(header):
        with open(header, encoding="utf-8") as f:
            current = f.read()
    if current != text:
        with open(header, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("gauge_version: firmware %s" % version)


main()
